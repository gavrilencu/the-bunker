// Generates assets/CREDITS_media.md from the texture / HDRI / audio manifests.
import fs from 'node:fs';
import path from 'node:path';
import { ASSETS, readJSON } from './lib.mjs';
import { SOURCES } from './sources.mjs';

const tex = readJSON(path.join(ASSETS, 'textures', 'manifest.json'));
const hdr = readJSON(path.join(ASSETS, 'hdri', 'manifest.json'));
const aud = readJSON(path.join(ASSETS, 'audio', 'manifest.json'));
const esc = s => String(s ?? '').replace(/\|/g, '\\|');

let md = `# Media credits (textures, HDRIs, audio)

Generated by \`tools/media/credits.mjs\` from the manifests in \`assets/textures\`, \`assets/hdri\`, \`assets/audio\`.
All assets are CC0 / public domain unless listed otherwise; CC BY / CC BY-SA items require the attribution below.

## Textures (PBR, 2K)

| id | source | author | license |
|---|---|---|---|
`;
for (const [id, m] of Object.entries(tex)) md += `| ${id} | [${esc(m.title)}](${m.source_url}) | ${esc(m.author)} | ${m.license} |\n`;

md += `\n## HDRI skies\n\n| id | source | author | license |\n|---|---|---|---|\n`;
for (const [id, m] of Object.entries(hdr)) md += `| ${id} | [${esc(m.title)}](${m.source_url}) | ${esc(m.author)} | ${m.license} |\n`;

md += `\n## Audio\n\n| id | description | author(s) | license | source(s) |\n|---|---|---|---|---|\n`;
for (const [id, m] of Object.entries(aud).sort()) {
  const links = String(m.source_url).split(' ; ').map((u, i) => u.startsWith('http') ? `[${i + 1}](${u})` : u).join(' ');
  md += `| ${id} | ${esc(m.title)} | ${esc(m.author)} | ${esc(m.license)} | ${links} |\n`;
}

// Attribution block: every registered source with a BY license that some audio file actually uses
const used = Object.values(aud).map(m => String(m.source_url)).join(' ; ');
md += `\n## Required attributions (CC BY / CC BY-SA)\n\n`;
for (const src of Object.values(SOURCES)) {
  if (!/BY/.test(src.license) || !used.includes(src.source_url)) continue;
  if (src.notes) md += `- ${src.notes}\n`;
  else md += `- "${src.title}" by ${src.author} — ${src.license} — ${src.source_url}\n`;
}
md += `\nCC BY-SA note: \`explosion_nuclear.ogg\` contains a processed excerpt of "Thunder Claps" by Jonathan Hunt (CC BY-SA 4.0); that derived audio file is itself shared under CC BY-SA 4.0.\n`;
md += `\nProcedural sounds/layers (geiger_click, ui_hover, radio_static, sub-boom, rumble, roar, thump, hum, power sweeps) were synthesized by \`tools/media/synth.mjs\` and are released CC0.\n`;

fs.writeFileSync(path.join(ASSETS, 'CREDITS_media.md'), md);
console.log('wrote assets/CREDITS_media.md');
